package com.cashu.me.liveintegration

import androidx.test.platform.app.InstrumentationRegistry
import com.cashu.me.Core.NostrService
import kotlinx.coroutines.delay
import kotlinx.coroutines.runBlocking
import kotlinx.serialization.json.*
import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.FixMethodOrder
import org.junit.runners.MethodSorters

/** Paired with the Swift suite: actual native bindings, independent seeds and SQLite. */
@FixMethodOrder(MethodSorters.NAME_ASCENDING)
class CrossPlatformInteropTest : PaymentFixtureTest() {
    @Test fun cdkNativePlatformInteroperability() = runBlocking { exchange("cdk", 3339) }
    @Test fun nutshellNativePlatformInteroperability() = runBlocking { exchange("nutshell", 3338) }

    private suspend fun exchange(mint: String, port: Int) {
        assumeTrue("Run with the paired iOS interoperability suite",
            InstrumentationRegistry.getArguments().getString("cashu.interopSessionId") != null)
        val shared = requireNotNull(InstrumentationRegistry.getArguments().getString("cashu.interopSessionId")) {
            "Run the paired native interoperability suite"
        }
        val bridge = "/sessions/$shared"
        val receiver = wallet(mint, "http://127.0.0.1:$port")
        // Public test vector; wallet seed itself is freshly generated by the gateway.
        val key = "0".repeat(63) + "1"
        val publicKey = "02" + NostrService.publicKeyHex(key)
        call("$bridge/receive", "POST", buildJsonObject { put("stage", "$mint-android-key"); put("key", publicKey) })
        val peerKey = waitFor("$mint-ios-key", bridge).getValue("key").jsonPrimitive.content
        val incoming = waitFor("$mint-ios-tokens", bridge)
        val plain = incoming.getValue("plain").jsonPrimitive.content
        val locked = incoming.getValue("locked").jsonPrimitive.content
        assertEquals(31, receiver.receive(plain))
        expectError("key", "signature", "witness", "sign", "p2pk") {
            receiver.receive(locked, listOf("0".repeat(63) + "2"))
        }
        assertEquals(7, receiver.receive(locked, listOf(key)))
        expectError("spent", "used", "11001", "already") { receiver.receive(plain) }
        receiver.reopen()
        assertEquals(38, receiver.balance())
        val reply = receiver.send(13).token
        val replyLocked = receiver.send(5, peerKey).token
        assertEquals(20, receiver.balance())
        call("$bridge/receive", "POST", buildJsonObject {
            put("stage", "$mint-android-tokens"); put("plain", reply); put("locked", replyLocked)
            put("balance", receiver.balance())
        })
        val completed = waitFor("$mint-ios-complete", bridge)
        assertEquals(108, completed.getValue("balance").jsonPrimitive.long)
        receiver.reopen()
        assertEquals(20, receiver.balance())
        assertEquals(128, receiver.balance() + completed.getValue("balance").jsonPrimitive.long)
    }

    private suspend fun waitFor(stage: String, bridge: String): JsonObject {
        repeat(480) {
            val deliveries = call(bridge).getValue("deliveries").jsonArray
            deliveries.map { it.jsonObject }.firstOrNull { it["stage"]?.jsonPrimitive?.content == stage }?.let { return it }
            delay(500)
        }
        error("Timed out waiting for $stage")
    }
}
